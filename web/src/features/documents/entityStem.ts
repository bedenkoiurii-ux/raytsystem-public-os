// Зіставлення слів за основою — спільне для підсвітки й для діалогу.
//
// Рішення Юрія 2026-08-03: підсвічується кожне входження в БУДЬ-ЯКОМУ відмінку,
// зокрема коли міняється закінчення не останнього слова («Великому терору»,
// «Голодомором»). Індекс імен зберігає поверхневі форми, тож без основ
// давальний відмінок стояв темним, ніби картки немає.
//
// **Основа порівнюється цілим словом, по межах слова, а не підрядком.** Це
// пряма вимога, і вона не косметична: підрядкове зіставлення — це рівно той
// клас, що дав «[[Крим|кримінальну]]» (KI-18).
//
// Правило однакової лексеми: спільний початок щонайменше на чотири літери, і
// хвіст **з обох боків** не довший за три. Перевірено на живих парах:
//
//   великому / великий    → спільне «велик», хвости «ому»/«ий»   ✓ та сама
//   голодомором / голодомор → спільне «голодомор», хвости «ом»/«» ✓ та сама
//   голодний / голодомор  → спільне «голод», хвіст «омор» = 4     ✗ інша
//   кримінальну / крим    → спільне «крим», хвіст «інальну» = 7   ✗ інша
//   скіфія / скіфський    → спільне «скіф», хвіст «ський» = 5     ✗ інша
//
// Слова, коротші за чотири літери, зіставляються лише дослівно: там кожна
// літера — це вже інше слово.

/** Скільки літер мусить збігтися, щоб рахувати початок спільним коренем. */
const MIN_ROOT = 4;
/** Найдовший дозволений хвіст після спільного кореня — з кожного боку. */
const MAX_TAIL = 3;

function commonPrefix(a: string, b: string): number {
  const limit = Math.min(a.length, b.length);
  let i = 0;
  while (i < limit && a[i] === b[i]) i += 1;
  return i;
}

/** Чи це те саме слово в різних відмінках.
 *
 *  `strict` — для форм-прізвищ: слово в тексті не буває КОРОТШИМ за прізвище,
 *  бо відмінок додає закінчення, а не відрізає. Без цього «Богу» лягало на
 *  «Богун» 44 рази (замір 03.08).
 */
export function sameLexeme(a: string, b: string, strict = false): boolean {
  if (strict && a !== b && a.length < b.length) return false;
  return looseLexeme(a, b);
}

function looseLexeme(a: string, b: string): boolean {
  if (a === b) return true;
  if (a.length < MIN_ROOT || b.length < MIN_ROOT) return false;   // короткі — лише дослівно
  // Числа зіставляються лише дослівно. Інакше «1169» ставало посиланням на
  // подію через форму «1169-го»: рік у тексті — це рік, а не назва події
  // (контроль 03.08: 115 хибних збігів).
  if (/\d/.test(a) || /\d/.test(b)) return false;
  const root = commonPrefix(a, b);
  if (root < MIN_ROOT) return false;
  const tailA = a.length - root;
  const tailB = b.length - root;
  if (tailA > MAX_TAIL || tailB > MAX_TAIL) return false;
  // Хвіст з ОБОХ боків при корені лише в чотири літери — це вже інше слово,
  // а не відмінок. Контроль 03.08 назвав ціну цієї поблажки поіменно:
  // «потім» ← «потій» (184 рази) і «history» ← «histria» (113). Коли ж один бік
  // є початком другого (хвіст нульовий), чотирьох літер досить: «крим» / «криму».
  if (tailA > 0 && tailB > 0 && root < MIN_ROOT + 1) return false;
  return true;
}

/** Ключ відра: перші літери слова. Звужує перебір, не вирішуючи збіг. */
export function bucketKey(word: string): string {
  return word.slice(0, MIN_ROOT);
}

export function words(text: string): string[] {
  return text.toLowerCase().match(/[\p{L}\p{N}'’-]+/gu) ?? [];
}

/** Чи послідовність слів тексту є тією самою назвою, що й слова форми. */
export function sameWords(got: string[], want: string[], strict = false): boolean {
  if (got.length !== want.length) return false;
  for (let i = 0; i < got.length; i += 1) {
    if (!sameLexeme(got[i], want[i], strict)) return false;
  }
  return true;
}
