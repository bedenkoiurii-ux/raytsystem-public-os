// Очищення виділеного тексту до назви-терміна (рішення Юрія 2026-08-03).
//
// Людина виділяє мишею, а миша чіпляє зайве: пробіл перед словом, кому після,
// відкриту дужку без пари. Термін замовлення — це НАЗВА, і сміття на краях у
// назву не входить.
//
// **Оригінал не втрачається.** Очищується лише назва; виділення, як його зробила
// рука, лишається в цитаті-контексті реєстру — саме звідти потім видно, звідки
// термін узявся.
//
// **Усередині не чіпаємо нічого.** Лапки й дужки в глибині — частина назви:
// «Правила мистецтва» всередині `«Правила мистецтва», 1992` мусять лишитись, бо
// це і є назва книжки. Автомат ріже тільки краї; зміст ріже рука.

/** Відкривач → його закривач. Симетричні лапки — самі собі пара. */
const PAIRS: Record<string, string> = {
  "(": ")", "[": "]", "{": "}",
  "«": "»", "“": "”", "„": "“", "‘": "’", "‚": "’",
  '"': '"', "'": "'", "’": "’",
};
const CLOSERS = new Set(Object.values(PAIRS));
/** Крайня пунктуація: те, що прилипає до назви, але назвою не є. */
const EDGE_PUNCT = /^[\s,.;:!?—–-]+|[\s,.;:!?—–-]+$/g;

function balanced(text: string, open: string, close: string): boolean {
  if (open === close) return (text.split(open).length - 1) % 2 === 0;
  return (text.split(open).length - 1) === (text.split(close).length - 1);
}

/** Пара обгортає ВЕСЬ термін: «Назва» — так, «Назва», 1992 — ні.
 *
 *  Рахуємо ГЛИБИНОЮ, а не кількістю. Кількість бреше на `«Назва» і «Інша»`:
 *  всередині там одна « і одна », тобто «збалансовано», — і перевірка за
 *  кількістю знімала б лапки з двох різних назв, лишаючи `Назва» і «Інша`.
 *  Глибина каже правду: перша лапка закривається посеред рядка, отже обгорткою
 *  вона не є.
 */
function wraps(text: string): boolean {
  const open = text[0];
  const close = PAIRS[open];
  if (!close || text.length < 2 || text[text.length - 1] !== close) return false;
  if (open === close) {
    // Симетричні лапки глибини не мають: обгортка — рівно дві, по краях.
    return text.split(open).length - 1 === 2;
  }
  let depth = 0;
  for (let i = 0; i < text.length; i += 1) {
    if (text[i] === open) depth += 1;
    else if (text[i] === close) depth -= 1;
    if (depth === 0 && i < text.length - 1) return false;   // закрилась раніше кінця
  }
  return depth === 0;
}

/**
 * Виділення → назва-термін.
 *
 * Порядок кроків важливий і перевірений на прикладах Юрія: спершу пробіли,
 * далі непарні краї, тоді обгортка, наприкінці пунктуація — і все це по колу,
 * бо зняття одного шару відкриває наступний: `(«Назва»` спершу губить дужку,
 * і аж тоді видно, що лапки збалансовані й чіпати їх не можна.
 */
export function cleanTerm(raw: string): string {
  // Переноси й подвійні пробіли — в один пробіл: виділення через рядки не має
  // ставати багаторядковим терміном.
  let text = raw.replace(/\s+/g, " ").trim();
  for (let guard = 0; guard < 12; guard += 1) {
    const before = text;

    if (wraps(text)) text = text.slice(1, -1).trim();

    // Сирота на початку: відкривач, чиєї пари в тексті немає.
    const head = text[0];
    if (head && PAIRS[head] && !balanced(text, head, PAIRS[head])) {
      text = text.slice(1).trim();
    }
    // Сирота в кінці: закривач без свого відкривача.
    const tail = text[text.length - 1];
    if (tail && CLOSERS.has(tail)) {
      const open = Object.keys(PAIRS).find((key) => PAIRS[key] === tail);
      if (open && !balanced(text, open, tail)) text = text.slice(0, -1).trim();
    }

    text = text.replace(EDGE_PUNCT, "");
    if (text === before) break;
  }
  return text;
}
