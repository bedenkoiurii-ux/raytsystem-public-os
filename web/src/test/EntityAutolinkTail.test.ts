// Правило хвоста в автопідсвітці — межі, заміряні 03.08 на трьох документах.
//
// Без хвоста відмінок, якого автор не підписав руками, лишався темним і читався
// як «картки немає». З необмеженим хвостом транскрипт ПП дав 37 хибних збігів.
// Тому: хвіст до трьох літер і лише для форм від пʼяти знаків.
import { describe, expect, it } from "vitest";
import { autolink } from "../features/InlineEntity";

const forms = {
  "вишгород": "Вишгород",
  "володимир": "Володимир Великий",
  "рим": "Рим",
  "твер": "Твер",
  "крим": "Крим",
  "максим": "Максим (митрополит)",
};
const proper = new Set(Object.keys(forms));
const link = (text: string) => autolink(text, forms, proper);

describe("правило хвоста", () => {
  it("бере відмінок, якого немає в індексі", () => {
    expect(link("Андрій у Вишгороді")).toContain("[[Вишгород|Вишгороді]]");
    expect(link("втік із Вишгорода")).toContain("[[Вишгород|Вишгорода]]");
  });

  it("не бере коротку форму всередині чужого слова", () => {
    expect(link("чотирма рядами")).toBe("чотирма рядами");       // «рим»
    expect(link("затвердили список")).toBe("затвердили список"); // «твер»
    expect(link("кримінальну справу")).toBe("кримінальну справу"); // «крим», 4 знаки
  });

  it("не бере довгий хвіст навіть у довгої форми", () => {
    expect(link("Володимирович прийшов")).toBe("Володимирович прийшов");
  });

  it("ціле слово працює як працювало", () => {
    expect(link("місто Вишгород")).toContain("[[Вишгород]]");
  });

  it("власна назва з малої лишається загальним словом", () => {
    expect(link("на максимі можливого")).toBe("на максимі можливого");
  });

  it("вже наявний вікілінк не чіпається", () => {
    expect(link("у [[Вишгород|Вишгороді]] було")).toBe("у [[Вишгород|Вишгороді]] було");
  });

  it("код, посилання й заголовки лишаються як є", () => {
    expect(link("`Вишгород`")).toBe("`Вишгород`");
    expect(link("# Вишгород")).toBe("# Вишгород");
    expect(link("https://ex.org/Вишгород")).toBe("https://ex.org/Вишгород");
  });
});
