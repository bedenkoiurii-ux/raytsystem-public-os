// Омоніми «загальна назва ↔ власна назва» — розрізняє регістр у тексті.
//
// Привід: Юрій не зміг завести поняття «максима» — форма «максима» лежить в
// індексі як родовий відмінок митрополита Максима, і три рубежі перевірки
// згасили кнопку «Нова сутність». Кнопку відкрито назавжди (перевірка це
// підказка, не брама), а тут — наслідок, що прилітає одразу: коли поняття
// з'явиться, форма стане спірною між ним і людиною.
//
// Правило: з малої — поняття; з великої посеред речення — ім'я; на початку
// речення регістр не означає нічого, і там тиша.
import { describe, expect, it } from "vitest";
import { autolink, type Homonym } from "../features/InlineEntity";

const forms: Record<string, string> = {
  "максима": "Максима (поняття)",
  "максим": "Максим (митрополит)",
  "київ": "Київ",
};
const proper = new Set(["максим", "київ"]);
const homonyms: Record<string, Homonym> = {
  "максима": { common: "Максима (поняття)", proper: "Максим (митрополит)" },
};
const link = (t: string) => autolink(t, forms, proper, undefined, homonyms);

describe("омонім розрізняється регістром", () => {
  it("з малої — поняття", () => {
    expect(link("житейська максима каже")).toContain("[[Максима (поняття)|максима]]");
  });

  it("з великої посеред речення — власна назва", () => {
    expect(link("грамота митрополита Максима")).toContain("[[Максим (митрополит)|Максима]]");
  });

  it("на початку речення — тиша, бо регістр там нічого не каже", () => {
    expect(link("Максима каже: не поспішай.")).toBe("Максима каже: не поспішай.");
  });

  it("після крапки — теж початок речення", () => {
    expect(link("Так було. Максима лишилась.")).toBe("Так було. Максима лишилась.");
  });

  it("після коми — не початок речення, регістр вирішує", () => {
    expect(link("грамота, Максима підписав")).toContain("[[Максим (митрополит)|Максима]]");
  });

  it("не-омоніми працюють як працювали", () => {
    expect(link("Київ стоїть")).toContain("[[Київ]]");
    // З малої власна назва не лінкується — запобіжник регістру, що був і до нас.
    expect(link("київ якийсь")).toBe("київ якийсь");
  });

  it("без словника омонімів поведінка не змінюється", () => {
    const out = autolink("житейська максима", forms, proper);
    expect(out).toContain("[[Максима (поняття)|максима]]");
  });
});
