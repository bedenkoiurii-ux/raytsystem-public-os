// Підсвітка за основами — і чотири класи хибних збігів, знайдені контролем 03.08.
//
// Кожен випадок нижче колись світився неправильно на всій бібліотеці. Тест
// тримає саме їх, бо правило основи легко послабити назад, не помітивши: воно
// виглядає як одна цифра, а коштує сотнями хибних підсвіток.
import { describe, expect, it } from "vitest";
import { sameLexeme } from "../features/documents/entityStem";
import { autolink } from "../features/InlineEntity";

const forms: Record<string, string> = {
  "великий терор": "Великий терор",
  "великого терору": "Великий терор",
  "великий розкол": "Великий розкол 1054",
  "голодомор": "Голодомор",
  "потій": "Іпатій Потій",
  "потієм": "Іпатій Потій",
  "histria": "Істр (Дунай)",
  "1169-го": "Розгром Києва Боголюбським",
  "берестечка": "Берестецька битва",
  "берестечко": "Берестечко",
  "крим": "Крим",
  "москва": "Москва",
};
const proper = new Set(Object.keys(forms));
const link = (text: string) => autolink(text, forms, proper);

describe("правило основи", () => {
  it("відмінок будь-якого слова назви, не лише останнього", () => {
    expect(sameLexeme("великому", "великий")).toBe(true);
    expect(sameLexeme("голодомором", "голодомор")).toBe(true);
    expect(sameLexeme("москви", "москва")).toBe(true);
  });

  it("інша лексема з тим самим початком — не відмінок", () => {
    expect(sameLexeme("потім", "потій")).toBe(false);      // 184 хибні збіги
    expect(sameLexeme("history", "histria")).toBe(false);  // 113
    expect(sameLexeme("голодний", "голодомор")).toBe(false);
    expect(sameLexeme("кримінальну", "крим")).toBe(false); // клас KI-18
    expect(sameLexeme("скіфія", "скіфський")).toBe(false);
  });

  it("числа зіставляються лише дослівно", () => {
    expect(sameLexeme("1169", "1169-го")).toBe(false);     // 115 хибних збігів
    expect(sameLexeme("1169", "1169")).toBe(true);
  });

  it("короткі слова — лише дослівно", () => {
    expect(sameLexeme("рим", "риму")).toBe(false);
    expect(sameLexeme("крим", "криму")).toBe(true);        // корінь 4, хвіст лише з одного боку
  });
});

describe("підсвітка за основами", () => {
  it("«Великому терору» світиться, хоч такої форми в індексі немає", () => {
    expect(forms["великому терору"]).toBeUndefined();
    expect(link("присвячено Великому терору 1937 року"))
      .toContain("[[Великий терор|Великому терору]]");
  });

  it("сусідні сутності від нього не світяться", () => {
    const out = link("присвячено Великому терору");
    expect(out).not.toContain("Великий розкол");
    expect(out).not.toContain("[[Крим");
  });

  it("«потім» лишається прислівником", () => {
    expect(link("Спершу одне, потім інше")).toBe("Спершу одне, потім інше");
  });

  it("рік не стає посиланням на подію", () => {
    expect(link("У 1169 році сталося")).toBe("У 1169 році сталося");
  });

  it("неоднозначне мовчить: «Берестечком» стелиться і на місто, і на битву", () => {
    expect(link("під Берестечком")).toBe("під Берестечком");
  });

  it("дослівна форма виграє в збігу за основою", () => {
    expect(link("місто Берестечко")).toContain("[[Берестечко]]");
  });

  it("вже наявний вікілінк, код і заголовок лишаються як є", () => {
    expect(link("у [[Великий терор|Великому терору]] було")).toBe("у [[Великий терор|Великому терору]] було");
    expect(link("`Великому терору`")).toBe("`Великому терору`");
    expect(link("# Великому терору")).toBe("# Великому терору");
  });

  it("власна назва з малої лишається загальним словом", () => {
    expect(link("кримські татари")).toBe("кримські татари");
  });
});
