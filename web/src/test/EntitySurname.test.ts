// Форми-прізвища: картки звуться повним ім'ям, а текст живе прізвищем.
// Класи хибних, знайдені заміром 03.08, тримає кожен свій випадок.
import { describe, expect, it } from "vitest";
import { sameLexeme } from "../features/documents/entityStem";
import { autolink } from "../features/InlineEntity";

const forms: Record<string, string> = {
  "джордж орвелл": "Джордж Орвелл",
  "орвелл": "Джордж Орвелл",
  "абрагам маслоу": "Абрагам Маслоу",
  "маслоу": "Абрагам Маслоу",
  "іван богун": "Іван Богун",
  "богун": "Іван Богун",
  "володимир мономах": "Володимир Мономах",
  "мономах": "Володимир Мономах",
};
const proper = new Set(Object.keys(forms));
const surnames = new Set(["орвелл", "маслоу", "богун", "мономах"]);
const link = (t: string) => autolink(t, forms, proper, surnames);

describe("прізвище як форма", () => {
  it("однослівне прізвище світиться", () => {
    expect(link("Орвелл писав про це")).toContain("[[Джордж Орвелл|Орвелл]]");
    expect(link("за Маслоу")).toContain("[[Абрагам Маслоу|Маслоу]]");
  });

  it("прізвище у відмінку теж", () => {
    expect(link("похід Мономаха")).toContain("[[Володимир Мономах|Мономаха]]");
    expect(link("полк Богуна")).toContain("[[Іван Богун|Богуна]]");
  });

  it("повне ім'я лишається цілим, а не рветься на прізвище", () => {
    expect(link("Джордж Орвелл писав")).toContain("[[Джордж Орвелл]]");
  });

  it("слово, КОРОТШЕ за прізвище, ним не є", () => {
    // «Богу» (давальний від Бог) лягало на «Богун» 44 рази.
    expect(link("слава Богу")).toBe("слава Богу");
    expect(sameLexeme("богу", "богун", true)).toBe(false);
    expect(sameLexeme("богу", "богун")).toBe(true);   // без суворого режиму — лягає
  });

  it("ім'я окремо не є формою ніколи", () => {
    expect(forms["джордж"]).toBeUndefined();
    expect(forms["абрагам"]).toBeUndefined();
  });

  it("з малої літери прізвище лишається загальним словом", () => {
    expect(link("богун якийсь")).toBe("богун якийсь");
  });
});

describe("топонім-метонімія", () => {
  // Гола форма топоніма веде на МІСЦЕ; подія бере лише власні форми
  // (рішення Юрія 2026-08-03). Індекс вирішує це при збиранні, тож тут
  // перевіряємо наслідок: обидві картки живуть, кожна зі своїми формами.
  const forms: Record<string, string> = {
    "катинь": "Катинь",
    "катині": "Катинь",
    "катинський розстріл": "Катинський розстріл",
    "катинського розстрілу": "Катинський розстріл",
  };
  const proper = new Set(Object.keys(forms));
  const link = (t: string) => autolink(t, forms, proper);

  it("гола форма топоніма веде на місце", () => {
    expect(link("розслідування Катині")).toContain("[[Катинь|Катині]]");
  });

  it("власна форма події лишається за подією", () => {
    expect(link("жертви Катинського розстрілу")).toContain("[[Катинський розстріл|");
  });

  it("довша назва події виграє в голого топоніма", () => {
    const out = link("Катинський розстріл 1940");
    expect(out).toContain("[[Катинський розстріл]]");
    expect(out).not.toContain("[[Катинь|Катинський]]");
  });
});
