// Підсвітка всередині markdown-таблиці — скарга Юрія 03.08.
//
// Рядок реєстру замовлень розпався на зайві колонки: автопідсвітка вставила в
// клітинку `[[Василь-Костянтин Острозький|Острозької]]`, і труба всередині
// вікілінка стала роздільником колонки. Файл на диску був цілий — ламався
// рендер.
import { describe, expect, it } from "vitest";
import { autolink } from "../features/InlineEntity";

const forms: Record<string, string> = {
  "острозької": "Василь-Костянтин Острозький",
  "острог": "Острог",
  "москва": "Москва",
};
const proper = new Set(Object.keys(forms));
const link = (t: string) => autolink(t, forms, proper);

describe("вікілінк у клітинці таблиці", () => {
  it("труба екранується, рядок лишається на своїх колонках", () => {
    const row = "| Острозька академія | Заснування Острозької академії.md | текст |";
    const out = link(row);
    expect(out).toContain("[[Василь-Костянтин Острозький\\|Острозької]]");
    // Колонок стільки ж, скільки було: рахуємо НЕекрановані труби.
    const bars = (s: string) => (s.match(/(?<!\\)\|/g) ?? []).length;
    expect(bars(out)).toBe(bars(row));
  });

  it("поза таблицею труба лишається звичайною", () => {
    const out = link("заснування Острозької академії");
    expect(out).toContain("[[Василь-Костянтин Острозький|Острозької]]");
    expect(out).not.toContain("\\|");
  });

  it("рядок із відступом теж рахується таблицею", () => {
    const out = link("   | Острог | текст |");
    expect(out).not.toMatch(/(?<!\\)\|\s*Острог/);
  });

  it("збіг, що дорівнює назві картки, труби не має взагалі", () => {
    const out = link("| Острог | місто |");
    expect(out).toContain("[[Острог]]");
    const bars = (s: string) => (s.match(/(?<!\\)\|/g) ?? []).length;
    expect(bars(out)).toBe(3);
  });

  it("текст після таблиці знову без екранування", () => {
    const out = link("| Острог |\n\nМосква стоїть");
    expect(out).toContain("[[Москва]]");
  });
});
