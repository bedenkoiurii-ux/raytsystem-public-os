// Очищення виділеного до назви-терміна — приклади Юрія 03.08 і межі навколо них.
import { describe, expect, it } from "vitest";
import { cleanTerm } from "../features/documents/entityTerm";

describe("очищення терміна", () => {
  it("приклад Юрія: зовнішня дужка й лапка-сирота зняті, кома з роком лишилась", () => {
    // Кома з роком — це ВМІСТ виділення, її ріже рука, не автомат.
    expect(cleanTerm("(«Правила мистецтва», 1992")).toBe("«Правила мистецтва», 1992");
  });

  it("приклад Юрія: пробіли й кома на краях", () => {
    expect(cleanTerm(" Маслоу, ")).toBe("Маслоу");
  });

  it("приклад Юрія: чисте слово лишається як було", () => {
    expect(cleanTerm("Маслоу")).toBe("Маслоу");
    expect(cleanTerm("Девід Гʼюм")).toBe("Девід Гʼюм");
  });

  it("пара, що обгортає весь термін, знімається", () => {
    expect(cleanTerm("«Правила мистецтва»")).toBe("Правила мистецтва");
    expect(cleanTerm('"Бурдьє"')).toBe("Бурдьє");
    expect(cleanTerm("(Бурдьє)")).toBe("Бурдьє");
    expect(cleanTerm("[Бурдьє]")).toBe("Бурдьє");
  });

  it("лапки й дужки ВСЕРЕДИНІ не чіпаються ніколи", () => {
    expect(cleanTerm("Бурдьє, «Правила мистецтва»")).toBe("Бурдьє, «Правила мистецтва»");
    expect(cleanTerm("Габітус (за Бурдьє)")).toBe("Габітус (за Бурдьє)");
    expect(cleanTerm("«Правила мистецтва» і «Дистинкція»")).toBe("«Правила мистецтва» і «Дистинкція»");
  });

  it("непарний хвіст знімається так само, як голова", () => {
    expect(cleanTerm("Правила мистецтва»")).toBe("Правила мистецтва");
    expect(cleanTerm("Бурдьє)")).toBe("Бурдьє");
  });

  it("переноси й подвійні пробіли — в один пробіл", () => {
    expect(cleanTerm("П'єр\n  Бурдьє")).toBe("П'єр Бурдьє");
    expect(cleanTerm("Девід   Гʼюм\n")).toBe("Девід Гʼюм");
  });

  it("крайня пунктуація всіх видів", () => {
    expect(cleanTerm("Маслоу.")).toBe("Маслоу");
    expect(cleanTerm("— Маслоу;")).toBe("Маслоу");
    expect(cleanTerm("Маслоу:")).toBe("Маслоу");
    expect(cleanTerm("…Маслоу…")).toBe("…Маслоу…");   // три крапки — не крайня пунктуація списку
  });

  it("кілька шарів знімаються по колу", () => {
    expect(cleanTerm(" ((«Бурдьє»)) ")).toBe("Бурдьє");
    expect(cleanTerm('  "Маслоу",  ')).toBe("Маслоу");
  });

  it("дефіс усередині слова не чіпається", () => {
    expect(cleanTerm("Гʼюм-Ротшильд")).toBe("Гʼюм-Ротшильд");
    expect(cleanTerm("військово-політичний")).toBe("військово-політичний");
  });

  it("порожнє й сміття не валять функцію", () => {
    expect(cleanTerm("")).toBe("");
    expect(cleanTerm("   ")).toBe("");
    expect(cleanTerm("«»")).toBe("");
    expect(cleanTerm(",,,")).toBe("");
  });
});
